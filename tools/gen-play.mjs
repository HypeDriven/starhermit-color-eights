// Writes tests/native/journey-match.play: Journey stage 1 (First Dealing)
// played to its results through the real UI. The round is simulated here
// with the shipped rules (js/rules.js, js/content.js): each human turn plays
// the first legal card (clicked by its name, exactly) or draws (D); each AI
// turn is waited for until the turn label says "Your turn" again.
//   node tools/gen-play.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
require('../js/rules.js');
require('../js/content.js');
const R = globalThis.CERules, C = globalThis.CEContent;

const stage = C.JOURNEY[0];
const cfg = C.journeyConfig(stage);
const players = [{ id: 'p0', name: 'You', isAI: false }, { id: 'p1', name: 'Vex', isAI: true, aiLevel: stage.aiLevel || 'easy' }];
let s = R.createGame(cfg, players);
const label = (c) => `${R.COLOR_INFO[c.color].label} ${c.rank}`;
const out = [
  '# Generated by tools/gen-play.mjs: Journey stage 1 (First Dealing) played to its',
  '# results — each human turn the first legal card (clicked by its name) or D to',
  '# draw, each AI turn waited for until the turn label says "Your turn" again.',
  'until 300 Color Eights', 'frames 20', 'click Journey', 'until 60 Forty stages', 'frames 10',
  'click 1. First Dealing', 'until 60 Goal: win the round.', 'frames 10', 'click =Play', 'until 200 Your turn', 'frames 30', 'save stage-start',
];
let n = 0, turns = 0;
while (s.phase === 'active' && n < 400) {
  const pl = s.players[s.currentPlayer];
  let cmd;
  if (!pl.isAI) {
    const la = R.legalActions(s, pl.id);
    const play = la.actions.find((a) => a.type === 'play');
    out.push('until 600 Your turn', 'frames 10');
    if (play) { cmd = { type: 'play', cardId: play.cardId }; out.push(`click =${label(pl.hand.find((c) => c.id === play.cardId))}`); }
    else { cmd = { type: 'draw' }; out.push('key KeyD 2'); }
    out.push('frames 6');
    if (++turns === 4) out.push('save mid-round');
  } else cmd = R.aiChoose(s, pl.id, pl.aiLevel);
  cmd.id = 'g' + (++n); cmd.player = pl.id;
  const r = R.applyCommand(s, cmd);
  if (r.error) throw new Error(r.reason);
  s = r.state;
}
if (s.phase !== 'finished') throw new Error('round did not finish');
const won = s.winner === 'p0';
out.push(`until 900 ${won ? 'You win!' : 'Vex wins'}`, 'frames 30', 'expect Score:', 'save results', 'click Back to menu', 'until 60 Daily Challenge', 'frames 5');
writeFileSync(new URL('../tests/native/journey-match.play', import.meta.url), out.join('\n') + '\n');
console.log(`journey-match.play: ${turns} human turns, ${won ? 'won' : 'lost'} (${s.scores.total} points)`);
